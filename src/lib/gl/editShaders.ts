// Open_Edit photo-editor shaders. Standard techniques, written for this project:
//   - tone controls work on luma with hue-preserving gain, driven by a blurred "base" layer (two-scale decomposition)
//   - clarity / texture are local-contrast boosts of the base-to-detail difference at two radii
//   - highlights / shadows recover tones with luminance masks computed on the blurred base (halo-free enough at
//     these radii and much cheaper than a full local Laplacian)
//   - HSL uses seven overlapping hue bands with raised-cosine weights; split tone is a luma-masked soft-light tint
// All lookup tables (grain, skin tone) come from the asset pack and are generated by scripts/gen-luts.mjs.

const PREC = `
#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif
`;

/** 4x4 box average over the destination texel footprint (pre-filter for the blur pyramid). */
export const DOWN_FRAG = `${PREC}
varying highp vec2 textureCoordinate;
uniform sampler2D inputImageTexture;
uniform vec2 footprint;
void main() {
  vec4 acc = vec4(0.0);
  for (int j = 0; j < 4; j++) {
    for (int i = 0; i < 4; i++) {
      acc += texture2D(inputImageTexture, textureCoordinate + (vec2(float(i), float(j)) * 0.25 - 0.375) * footprint);
    }
  }
  gl_FragColor = acc * 0.0625;
}`;

/** Separable gaussian (sigma ~2 texels) using 5 bilinear taps that cover 9 texels. */
export const BLUR_FRAG = `${PREC}
varying highp vec2 textureCoordinate;
uniform sampler2D inputImageTexture;
uniform vec2 dir;
void main() {
  // weights / offsets of a 9-texel gaussian folded into linear-filtered pairs
  vec4 c = texture2D(inputImageTexture, textureCoordinate) * 0.2270;
  c += (texture2D(inputImageTexture, textureCoordinate + dir * 1.3846) + texture2D(inputImageTexture, textureCoordinate - dir * 1.3846)) * 0.3162;
  c += (texture2D(inputImageTexture, textureCoordinate + dir * 3.2308) + texture2D(inputImageTexture, textureCoordinate - dir * 3.2308)) * 0.0703;
  gl_FragColor = c;
}`;

/**
 * Lookup in a 512x512 colour cube (8x8 slices of 64x64; slice index = blue, x = red, y = green). Two slices are
 * fetched with bilinear filtering and blended along blue: trilinear interpolation.
 */
export const CUBE_GLSL = `
vec3 sampleCube(sampler2D cube, vec3 c) {
  c = clamp(c, 0.0, 1.0);
  float z = c.b * 63.0;
  float z0 = floor(z);
  float z1 = min(z0 + 1.0, 63.0);
  vec2 inner = c.rg * (63.0 / 512.0) + 0.5 / 512.0;
  vec2 s0 = vec2(mod(z0, 8.0), floor(z0 * 0.125)) * 0.125;
  vec2 s1 = vec2(mod(z1, 8.0), floor(z1 * 0.125)) * 0.125;
  return mix(texture2D(cube, s0 + inner).rgb, texture2D(cube, s1 + inner).rgb, z - z0);
}`;

/** Portrait tone pass: warm / cool and light / tan tables, plus a skin-tone preset (skin + background tables). */
export const TONE_FRAG = `${PREC}
varying highp vec2 textureCoordinate;
uniform sampler2D inputImageTexture;
uniform sampler2D coolWarmLut, tanLightLut, skinLut, bgLut;
uniform float coolWarm, tanLight, skinTone;
${CUBE_GLSL}
// skin likelihood from chroma (YCbCr ellipse around typical skin), independent of brightness
float skinLikelihood(vec3 c) {
  float cb = -0.169 * c.r - 0.331 * c.g + 0.5 * c.b;
  float cr = 0.5 * c.r - 0.419 * c.g - 0.081 * c.b;
  float d = length(vec2((cb + 0.08) / 0.09, (cr - 0.1) / 0.08));
  return clamp(1.6 - d, 0.0, 1.0) * smoothstep(0.08, 0.25, c.r);
}
void main() {
  vec4 src = texture2D(inputImageTexture, textureCoordinate);
  vec3 c = clamp(src.rgb, 0.0, 1.0);
  if (abs(coolWarm) > 0.005) c = mix(c, sampleCube(coolWarmLut, c), abs(coolWarm));
  if (abs(tanLight) > 0.005) c = mix(c, sampleCube(tanLightLut, c), abs(tanLight));
  if (skinTone > 0.005) {
    float k = skinLikelihood(c);
    c = mix(c, mix(sampleCube(bgLut, c), sampleCube(skinLut, c), k), skinTone);
  }
  gl_FragColor = vec4(c, src.a);
}`;

export const EDIT_FRAG = `${PREC}
varying highp vec2 textureCoordinate;
uniform sampler2D inputImageTexture;
uniform sampler2D blurred;   // base layer, sigma ~1.5% of the short side
uniform sampler2D coarse;    // base layer, sigma ~4% of the short side
uniform sampler2D grainTex;  // tileable grain noise (REPEAT)
uniform sampler2D curvesTex; // 256x1: R master, G red, B green, A blue
uniform vec2 resolution;
uniform float autoTone, brilliance, brightness, contrast, clarity, saturation, sharpen, detail,
  highlights, shadows, fade, grain, warmth, tint, vignette, useCurves, useHsl;
uniform vec3 hslShift[7];    // per band: hue, saturation, lightness (-1..1)
uniform vec3 splitShadowColor, splitHighlightColor;
uniform float splitShadow, splitHighlight;

const vec3 LUMA = vec3(0.2126, 0.7152, 0.0722);
float luma(vec3 c) { return dot(c, LUMA); }
float sat01(float x) { return clamp(x, 0.0, 1.0); }
float band(float lo, float hi, float x) { float t = sat01((x - lo) / (hi - lo)); return t * t * (3.0 - 2.0 * t); }

// change luma to y2: darkening scales the colour (keeps hue and saturation), lifting adds the same amount to every
// channel (keeps hue without blowing up the chroma of dark pixels); a soft clip toward white avoids hue shifts
vec3 withLuma(vec3 c, float y2) {
  float y = max(luma(c), 1e-4);
  vec3 o = y2 <= y ? c * (y2 / y) : c + (y2 - y) * mix(vec3(1.0), c / y, 0.25);
  float m = max(o.r, max(o.g, o.b));
  if (m > 1.0) o = mix(o / m, vec3(1.0), sat01((m - 1.0) * 0.5));
  return o;
}

vec3 rgb2hsv(vec3 c) {
  float mx = max(c.r, max(c.g, c.b)), mn = min(c.r, min(c.g, c.b)), d = mx - mn;
  float h = 0.0;
  if (d > 1e-5) {
    if (mx == c.r) h = mod((c.g - c.b) / d, 6.0);
    else if (mx == c.g) h = (c.b - c.r) / d + 2.0;
    else h = (c.r - c.g) / d + 4.0;
  }
  return vec3(h / 6.0, mx > 1e-5 ? d / mx : 0.0, mx);
}
vec3 hsv2rgb(vec3 c) {
  vec3 k = clamp(abs(mod(c.x * 6.0 + vec3(0.0, 4.0, 2.0), 6.0) - 3.0) - 1.0, 0.0, 1.0);
  return c.z * mix(vec3(1.0), k, c.y);
}

// white balance: gains on an approximately linear signal; warmth along blue-amber, tint along green-magenta
vec3 whiteBalance(vec3 c, float w, float t) {
  vec3 lin = pow(c, vec3(2.2));
  lin *= vec3(1.0 + 0.18 * w + 0.06 * t, 1.0 + 0.02 * w - 0.12 * t, 1.0 - 0.22 * w + 0.06 * t);
  return pow(max(lin, 0.0), vec3(1.0 / 2.2));
}

// tone recovery on the base layer: lift shadows / pull highlights where the neighbourhood is dark / bright
vec3 toneRecover(vec3 c, float baseY, float hi, float sh) {
  float y = luma(c);
  float shMask = 1.0 - band(0.05, 0.6, baseY);
  // highlights act on bright pixels in bright neighbourhoods only, so midtones keep their colour
  float hiMask = band(0.45, 0.95, baseY) * band(0.35, 0.85, y);
  float y2 = y;
  y2 += sh * shMask * (sh > 0.0 ? (1.0 - y) * 0.6 * sqrt(sat01(y + 0.02)) : y * 0.6);
  y2 += hi * hiMask * (hi > 0.0 ? (1.0 - y) * 0.45 : (y - 0.35) * 0.4);
  return withLuma(c, sat01(y2));
}

// smooth S-curve contrast on luma; negative values flatten toward mid grey
vec3 contrastCurve(vec3 c, float k) {
  float y = luma(c);
  float s = y * y * (3.0 - 2.0 * y);
  float y2 = k >= 0.0 ? mix(y, s, k * 1.1) : mix(y, 0.5 + (y - 0.5) * 0.55, -k);
  vec3 o = withLuma(c, y2);
  float chroma = 1.0 + 0.25 * k;
  return mix(vec3(luma(o)), o, chroma);
}

// brightness as a gamma on luma (keeps black and white points)
vec3 brightnessCurve(vec3 c, float k) {
  float y = luma(c);
  return withLuma(c, pow(sat01(y), exp2(-k * 1.1)));
}

// brilliance: adaptive tone, opens dark areas and holds bright ones relative to their neighbourhood
vec3 brillianceTone(vec3 c, float baseY, float k) {
  float y = luma(c);
  float lift = (1.0 - baseY) * (1.0 - baseY) * 0.35;
  float hold = baseY * baseY * 0.12;
  float y2 = y + k * (lift * (1.0 - y) - hold * y);
  vec3 o = withLuma(c, sat01(y2));
  return mix(vec3(luma(o)), o, 1.0 + 0.12 * k);
}

vec3 vibranceSat(vec3 c, float k) {
  float y = luma(c);
  float s = max(c.r, max(c.g, c.b)) - min(c.r, min(c.g, c.b));
  float f = k >= 0.0 ? 1.0 + k * (1.2 - s) : 1.0 + k;
  return mix(vec3(y), c, f);
}

// auto tone: recovers both ends of the range, adds a little contrast and vibrance
vec3 autoToneAdjust(vec3 c, float baseY, float k) {
  vec3 o = toneRecover(c, baseY, -0.25 * k, 0.35 * k);
  o = contrastCurve(clamp(o, 0.0, 1.0), 0.15 * k);
  return vibranceSat(o, 0.2 * k);
}

// seven hue bands: red, orange, yellow, green, cyan, blue, magenta (raised-cosine weights)
vec3 hslBands(vec3 c) {
  vec3 hsv = rgb2hsv(c);
  float hue = hsv.x * 360.0;
  float centers[7];
  centers[0] = 0.0; centers[1] = 32.0; centers[2] = 60.0; centers[3] = 125.0; centers[4] = 190.0; centers[5] = 235.0; centers[6] = 300.0;
  float dh = 0.0, ds = 0.0, dl = 0.0, wsum = 0.0;
  for (int i = 0; i < 7; i++) {
    float d = abs(hue - centers[i]);
    d = min(d, 360.0 - d);
    float w = d < 45.0 ? 0.5 + 0.5 * cos(d / 45.0 * 3.14159265) : 0.0;
    dh += hslShift[i].x * w; ds += hslShift[i].y * w; dl += hslShift[i].z * w; wsum += w;
  }
  if (wsum > 1.0) { dh /= wsum; ds /= wsum; dl /= wsum; }
  float colourful = sat01(hsv.y * 4.0);
  hsv.x = fract(hsv.x + dh * 30.0 / 360.0 * colourful + 1.0);
  hsv.y = sat01(hsv.y * (1.0 + ds * colourful));
  vec3 o = hsv2rgb(hsv);
  return withLuma(o, sat01(luma(o) * (1.0 + dl * 0.5 * colourful * hsv.y)));
}

vec3 applyCurves(vec3 c) {
  c = clamp(c, 0.0, 1.0);
  vec3 o = vec3(texture2D(curvesTex, vec2(c.r, 0.5)).g, texture2D(curvesTex, vec2(c.g, 0.5)).b, texture2D(curvesTex, vec2(c.b, 0.5)).a);
  return vec3(texture2D(curvesTex, vec2(o.r, 0.5)).r, texture2D(curvesTex, vec2(o.g, 0.5)).r, texture2D(curvesTex, vec2(o.b, 0.5)).r);
}

vec3 softLight(vec3 b, vec3 s) {
  return mix(b - (1.0 - 2.0 * s) * b * (1.0 - b), b + (2.0 * s - 1.0) * (sqrt(b) - b), step(0.5, s));
}
vec3 splitTone(vec3 c) {
  float y = luma(c);
  if (splitShadow > 0.005) c = mix(c, softLight(c, splitShadowColor), splitShadow * (1.0 - band(0.0, 0.6, y)));
  if (splitHighlight > 0.005) c = mix(c, softLight(c, splitHighlightColor), splitHighlight * band(0.4, 1.0, y));
  return c;
}

void main() {
  vec2 uv = textureCoordinate;
  vec4 src = texture2D(inputImageTexture, uv);
  vec3 c = clamp(src.rgb, 0.0, 1.0);
  vec3 base = texture2D(blurred, uv).rgb;
  float baseY = luma(base);

  if (abs(autoTone) > 0.005) c = autoTone > 0.0 ? mix(c, autoToneAdjust(c, baseY, 1.0), autoTone) : mix(c, mix(vec3(luma(c)), c, 0.85) * 0.96 + 0.02, -autoTone);
  if (abs(brilliance) > 0.005) c = brillianceTone(c, baseY, brilliance);
  if (sharpen > 0.005) c += (c - base) * sharpen * 1.2;
  if (abs(highlights) > 0.005 || abs(shadows) > 0.005) c = toneRecover(clamp(c, 0.0, 1.0), baseY, highlights, shadows);
  if (abs(brightness) > 0.005) c = brightnessCurve(clamp(c, 0.0, 1.0), brightness);
  if (abs(contrast) > 0.005) c = contrastCurve(clamp(c, 0.0, 1.0), contrast);
  if (abs(clarity) > 0.005) {
    float cy = luma(texture2D(coarse, uv).rgb);
    float y = luma(c);
    float mid = 1.0 - abs(2.0 * y - 1.0);
    float y2 = clarity > 0.0 ? y + (y - cy) * clarity * 1.4 * mid : mix(y, cy, -clarity * 0.6);
    c = withLuma(clamp(c, 0.0, 1.0), sat01(y2));
  }
  if (abs(detail) > 0.005) {
    float y = luma(c);
    float y2 = detail > 0.0 ? y + (y - baseY) * detail * 1.0 : mix(y, baseY, -detail * 0.5);
    c = withLuma(clamp(c, 0.0, 1.0), sat01(y2));
  }
  if (abs(warmth) > 0.005 || abs(tint) > 0.005) c = whiteBalance(clamp(c, 0.0, 1.0), warmth, tint);
  if (abs(saturation) > 0.005) c = vibranceSat(c, saturation);
  if (fade > 0.005) c = mix(c, mix(vec3(luma(c)), c, 0.8) * 0.86 + 0.1, fade);
  c = clamp(c, 0.0, 1.0);
  if (useCurves > 0.5) c = applyCurves(c);
  if (useHsl > 0.5) c = clamp(hslBands(c), 0.0, 1.0);
  c = splitTone(c);
  if (abs(vignette) > 0.005) {
    vec2 p = (uv - 0.5) * vec2(resolution.x / max(resolution.x, resolution.y), resolution.y / max(resolution.x, resolution.y)) * 2.0;
    float r = length(p) / 1.2;
    float m = band(0.35, 1.15, r) * abs(vignette);
    c = vignette > 0.0 ? c * (1.0 - 0.85 * m) : mix(c, vec3(1.0), m * 0.85);
  }
  if (grain > 0.005) {
    vec2 g = uv * resolution / 256.0 * 1.4;
    vec3 n = texture2D(grainTex, g).rgb - 0.5;
    float y = luma(c);
    float w = 4.0 * y * (1.0 - y) + 0.15;
    c += mix(vec3(n.g), n, 0.25) * grain * 0.35 * w;
  }
  gl_FragColor = vec4(clamp(c, 0.0, 1.0), src.a);
}`;

